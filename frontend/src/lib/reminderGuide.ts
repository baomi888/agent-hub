/**
 * 「打开提醒权限」的分步教程（/reminder 与 /settings/reminder 共用）。
 *
 * ## 2026-11-11 改版：日历订阅整条路删掉了
 *
 * 原来的教程三端都在教「去日历里加一条订阅」。那条路发的是**每天一条固定摘要**，
 * 和「给每条待办单独设提醒时间」是两码事——用户设了 14:30 提醒，日历里的
 * 20:00 摘要照旧，看起来就是「提醒不按我设的时间响」。
 *
 * 现在只有一个通道：浏览器通知（Web Push）。所以教程也只讲这一件事：
 * 在待办页的「设置 → 提醒权限」里把开关打开。
 *
 * ## 三端只讲真实可行的
 *
 *   · iPhone  —— iOS 16.4+ 装到主屏后走 APNs，能收
 *   · 电脑    —— Edge 走微软 WNS，能收；Chrome 在国内常连不上
 *   · 安卓    —— 底层一律 Google FCM，国内不通，换浏览器没用
 *
 * 安卓那一页写的是「多数收不到」，不是「这样做就能收」——给一个开了不响的
 * 开关，比没有开关更浪费时间。
 *
 * ## 为什么不留截图
 *
 * 旧版每一步配的是日历 App 的截图，现在整个流程都不进日历了，那些图全对不上。
 * 与其放一张「位置大概在那里」的示意图，不如把点哪里写清楚。
 */

