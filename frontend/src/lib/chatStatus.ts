// 后端 status 帧 → 给用户看的一句话
//
// 背景（2026-11-01）：带资料库提问时首帧要等 14.3 秒（纯对话 1.7 秒）。
// 那 14 秒里前端只显示一个「思考中…」的点阵，用户不知道它在干什么，很容易
// 以为卡死 —— 但后端其实一直在发 status 帧（"RAG 模式，正在检索知识库(bk_xxx)"、
// "检索到 3 条片段"…），只是前端从前没有接。
//
// 这些文案是给开发者看的：里面有「RAG 模式」这种实现术语和 kb_xxx 这种内部 id。
// 直接显示等于把架构图糊到用户脸上，所以统一翻译成"它此刻在为你做什么"。
// 没命中规则的一律丢弃 —— 宁可继续说上一句，也不要漏出内部黑话。

interface Rule {
  re: RegExp;
  say: string | ((m: RegExpMatchArray) => string);
}

/*
 * ★ `re` 匹配的是**后端 original 文案**，`say` 才是给用户看的。
 * 2026-11-14 界面统一改叫「资料库」，但下面这些 `re` 里的「知识库」必须原样保留 ——
 * 后端 status 帧还在发「正在检索知识库(bk_xxx)」，改了正则就一条都匹配不上，
 * 界面上那行状态会永远停在上一句。要改先改后端，再改这里。
 */
const RULES: Rule[] = [
  { re: /RAG 模式.*检索知识库/, say: "正在翻你的资料库…" },
  { re: /检索到\s*(\d+)\s*条片段/, say: (m) => `找到 ${m[1]} 段相关资料` },
  { re: /知识库未命中/, say: "资料库里没有直接依据" },
  { re: /检索相似度偏低/, say: "相关资料不太贴题，先当参考" },
  { re: /正在生成答案/, say: "正在组织答案…" },
  { re: /纯 LLM 模式/, say: "正在思考…" },
  { re: /Agent 模式.*规划任务/, say: "正在拆解任务…" },
  { re: /混合模式.*规划执行路径/, say: "正在规划步骤…" },
  { re: /图片理解模式/, say: "正在看图…" },
  { re: /知识库检索不可用|知识库检索失败/, say: "资料库暂时读不到，先凭理解回答" },
  { re: /执行异常|流程未产出结果|改用直接作答/, say: "换个方式接着做…" },
  { re: /正在联网|搜索中|调用.*搜索/, say: "正在联网找…" },
];

/** status 帧文案 → 界面文案；没有合适的译法就返回空串（调用方跳过这次更新） */
export function humanizeStatus(raw: string): string {
  const text = (raw || "").trim();
  if (!text) return "";
  for (const r of RULES) {
    const m = text.match(r.re);
    if (!m) continue;
    return typeof r.say === "function" ? r.say(m) : r.say;
  }
  return "";
}
