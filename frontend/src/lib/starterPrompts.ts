// 首屏「一句就能走」的启动问题（2026-11-08 激活线）。
//
// 为什么单独一个文件
// ----------------
// 原来这三句住在 components/chat/constants.tsx 的 EXAMPLES 里，而且点了只**预填**
// 输入框 —— 新用户还要再点一次发送，激活线断在最后一步。这里把它拆成纯数据，
// 组件（components/StarterPrompts.tsx）只负责画，页面层只负责「点了发什么」。
//
// 选句的两条硬要求
// ----------------
// 1. **不依赖任何前置操作**。旧示例是「帮我把这份笔记整理成知识卡片」—— 新用户手上
//    没有笔记，点下去只能得到"请先上传资料"，等于把他推向下一步而不是答案。
//    这里只放「说清处境就能开答」的三类校园场景。
// 2. **不带占位符**。出现「（你的课程名）」这种空，模型会先反问，用户又得打字。
//    整句是一个完整的问题，点下去直接能出正文。
//
// 内容口径：三条分别覆盖 备考 / 升学 / 应急，是学生最常问又最容易被"没准备好材料"
// 卡住的三件事；hint 保持 2 字，在 390 宽的三列便签里不会被截断。

export interface StarterPrompt {
  /** 便签眉题（2 字）：竖排、窄列都放得下 */
  hint: string;
  /** 点下去原样发出去的问题 */
  question: string;
}

export const STARTER_PROMPTS: readonly StarterPrompt[] = [
  { hint: "六级", question: "六级还有一个月，帮我排一个每天 40 分钟的复习计划" },
  { hint: "考研", question: "考研数学一轮怎么开始？给我一个两周能跟上的入门安排" },
  { hint: "期末", question: "期末只剩三天，怎么把一门课的重点压成一页复习清单？" },
];
