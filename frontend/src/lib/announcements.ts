/**
 * 更新公告的数据层。
 *
 * 一期公告 = 一个 `Announcement`，`id` 就是"已读"的判定单位：
 * 用户读完这一期，localStorage 里记下的就是这一期的 id；下一期换个新 id，
 * 所有人重新看到一次。所以**改内容必须换 id**，否则老用户不会再看见。
 *
 * 为什么写在前端而不是后端表：
 *   · 公告的发布节奏和发版绑在一起（改了什么就只有这次发版知道），
 *     前端常量跟代码走，天然不会出现"代码回滚了、公告还挂着讲新功能"。
 *   · 它不需要按人下发、不需要管理后台、不需要实时性 —— 一个版本一份文案。
 * 什么时候该搬到后端：需要做到「不发版也能推公告」或者「给一部分人灰度」时。
 *
 * ★ 每一期都是全屏强制（产品决定，见 AnnounceModal 顶部注释）：没有关闭按钮，
 *   滑到底才能进。这个决定的代价是**文案必须短**——没人愿意在一个关不掉的页面上
 *   读长文，一旦读烦了，用户会记住"这站每次进来都要拦我一次"，而不是记住改了什么。
 *   所以：一条正文不超过三行，能举例子就不写概括，能说"少一步"就不写"优化了流程"。
 *
 * ★ 语气：像同学在群里跟你讲话，不像产品周报。
 *   不写"本次更新聚焦于三大方向"这种句子；不用"赋能/闭环/体验升级"；
 *   不为了工整去凑三项排比。宁可句子短一点、有个具体动作。
 *   用户原话最好用——他们说"一抽一抽"，文案里就写"一抽一抽"。
 *
 * ★ 文案里可以用两种行内标记（只支持这两种，别加第三种）：
 *     **加粗**   → 短语级强调，落在"这词重要"
 *     ==着色==   → 玉米金强调，落在"这一处变了"
 *   一眼扫过去要有轻重差：通篇都加粗等于没有加粗。一条正文里最多两处。
 */

export interface AnnounceChange {
  /** 两位编号，如 "01"。用编号而不是项目符号，是让"一共几条"看得出来 */
  no: string;
  title: string;
  /** 一段话，不超过三行；支持 **加粗** 与 ==着色== */
  body: string;
  /** 补充条目，可空；同样支持行内标记 */
  points?: string[];
}

export interface Announcement {
  /** 已读标记的键的一部分。发布新一期时**必须**换成没被用过的值 */
  id: string;
  /** 显示给人看的期号 */
  label: string;
  /** 显示用的日期，写死成发布日期，不从构建时间推 */
  date: string;
  title: string;
  lead: string;
  changes: AnnounceChange[];
  /** 「顺手修的几处」——一行一条，不编号 */
  minors?: string[];
}

