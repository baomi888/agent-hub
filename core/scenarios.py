def get_scenario_prompt(scenario: str | None) -> str:
    """返回场景对应的 system prompt 后缀；未选 / 未知场景返回空串（安全降级）。"""
    if not scenario:
        return ""
    s = SCENARIOS.get(scenario)
    return s["prompt"] if s else ""
